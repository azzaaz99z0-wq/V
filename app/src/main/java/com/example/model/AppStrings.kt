object AppStrings {

    fun get(lang: AppLanguage, key: String): String {
        val dict = when (lang) {
            AppLanguage.ARABIC -> ARABIC_STRINGS
            AppLanguage.FRENCH -> FRENCH_STRINGS
            AppLanguage.GERMAN -> GERMAN_STRINGS
            AppLanguage.JAPANESE -> JAPANESE_STRINGS
            AppLanguage.CHINESE -> CHINESE_STRINGS
            AppLanguage.HINDI -> HINDI_STRINGS
            AppLanguage.ENGLISH -> ENGLISH_STRINGS
        }
        return dict[key] ?: ENGLISH_STRINGS[key] ?: key
    }

    fun getErrorByCode(lang: AppLanguage, code: String?): String {
        val key = when (code) {
            "network" -> "err_network_desc"
            "timeout" -> "err_timeout_desc"
            "http_416" -> "err_http_416_desc"
            "forbidden" -> "err_forbidden_desc"
            "rate_limit" -> "err_rate_limit_desc"
            "bot_check" -> "err_bot_check_desc"
            "private" -> "err_private_desc"
            "unavailable" -> "err_unavailable_desc"
            "geo_blocked" -> "err_geo_blocked_desc"
            "unsupported_url" -> "err_unsupported_url_desc"
            "format_unavailable" -> "err_format_unavailable_desc"
            else -> "err_general_desc"
        }
        return get(lang, key)
    }

